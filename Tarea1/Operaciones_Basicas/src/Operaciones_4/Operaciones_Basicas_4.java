public class Operaciones_Basicas_4 {
    public static void main(String[] args) {
        int valor1 = 10;
        int valor2 = 5;
        
        System.out.println(valor1 + " + " + valor2 + " = " + (valor1+valor2));
        System.out.println(valor1 + " - " + valor2 + " = " + (valor1-valor2));
        System.out.println(valor1 + " * " + valor2 + " = " + (valor1*valor2));
        System.out.println(valor1 + " / " + valor2 + " = " + (valor1/valor2));
    }
}
